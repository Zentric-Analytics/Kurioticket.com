import assert from "node:assert/strict";
import test from "node:test";
import { componentBundle, withComponentBrowser } from "../../test-support/componentBrowser";

test("inline admin search preserves keyboard focus, account recents, query cancellation, categories and errors", async () => {
  const bundle = componentBundle({ search: "src/components/admin/AdminWorkspaceSearch.tsx" });
  await withComponentBrowser(bundle, `const React=require('react'),{createRoot}=require('react-dom/client'),{flushSync}=require('react-dom'),S=require('search');
    window.requests=[];window.fetch=(url,options)=>new Promise(resolve=>window.requests.push({url,signal:options.signal,resolve}));
    sessionStorage.setItem('admin-search-recent:owner','["Owner recent"]');sessionStorage.setItem('admin-search-recent:other','["Other recent"]');
    const root=createRoot(document.getElementById('root'));window.mount=(account='owner')=>flushSync(()=>root.render(React.createElement(S.AdminWorkspaceSearchProvider,{account,key:account},React.createElement(S.AdminSearchTrigger),React.createElement(S.AdminSearchHeader,null,'Normal header'),React.createElement(S.AdminSearchContent,null,'Normal content'))));window.mount();`, async (page) => {
    const trigger = page.getByRole("button", { name: "Search Kurioticket admin" });
    await trigger.focus();
    await page.keyboard.press("Control+k");
    const input = page.getByRole("textbox", { name: "Search users, searches, providers" });
    await input.waitFor();
    assert.equal(await input.evaluate((node) => node === document.activeElement), true);
    assert.equal(await page.getByText("Owner recent", { exact: true }).count(), 1);
    assert.equal(await page.getByText("Other recent", { exact: true }).count(), 0);
    await input.fill("A & B");
    await page.waitForFunction("window.requests.length===1");
    assert.equal(await page.evaluate("window.requests[0].url"), "/api/admin/search?q=A%20%26%20B");
    await input.fill("current");
    await page.waitForFunction("window.requests.length===2");
    assert.equal(await page.evaluate("window.requests[0].signal.aborted"), true);
    await page.evaluate(`window.requests[1].resolve({ok:true,json:async()=>({users:[{id:'u',href:'/admin/users/u',title:'Current user',detail:'Fixture',status:'ACTIVE'}],searches:[],providers:[{id:'p',href:'/admin/providers',title:'Fixture provider',detail:'Fixture',status:'OK'}]})})`);
    await page.getByText("Current user", { exact: true }).waitFor();
    await page.getByRole("button", { name: "Providers", exact: true }).click();
    assert.equal(await page.getByText("Current user", { exact: true }).count(), 0);
    assert.equal(await page.getByText("Fixture provider", { exact: true }).count(), 1);
    await input.fill("denied");
    await page.waitForFunction("window.requests.length===3");
    await page.evaluate("window.requests[2].resolve({ok:false,status:403})");
    await page.getByRole("button", { name: "Retry" }).waitFor();
    assert.match(await page.locator('[aria-label="Admin search results"]').textContent() || "", /session has expired/);
    await page.getByRole("button", { name: "Retry" }).click();
    await page.waitForFunction("window.requests.length===4");
    await page.evaluate("window.requests[3].resolve({ok:false,status:503})");
    await page.getByText("Search is temporarily unavailable. Try again.", { exact: true }).last().waitFor();
    await page.keyboard.press("Escape");
    await trigger.waitFor();
    await page.waitForFunction("document.activeElement?.hasAttribute('data-admin-search-trigger')");
    await page.evaluate("window.mount('other')");
    await trigger.click();
    assert.equal(await page.getByText("Other recent", { exact: true }).count(), 1);
    assert.equal(await page.getByText("Owner recent", { exact: true }).count(), 0);
    await page.keyboard.press("Meta+k");
    assert.equal(await input.count(), 0);
  });
});
