const planningRoom = ({
  hotelId,
  id,
  name,
  bedConfiguration,
  features,
  mealPlan,
  cancellationInfo,
  basePrice,
  multiplier = 1,
}: {
  hotelId: string;
  id: string;
  name: string;
  bedConfiguration: string;
  features: string[];
  mealPlan: string;
  cancellationInfo: string;
  basePrice: number;
  multiplier?: number;
}): StaticHotelRoomOption => ({
  id: `${hotelId}-${id}`,
  name,
  bedConfiguration,
  features,
  mealPlan,
  cancellationInfo,
  taxesAndFeesIncluded: undefined,
  indicativeNightlyPrice: Math.round(basePrice * multiplier),
  currency: "USD",
});

