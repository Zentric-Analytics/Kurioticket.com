function verifiedCatalogueHotel(
  input: Omit<
    StaticHotelRecord,
    "slug" | "propertyType" | "currency" | "imageUrls" | "roomOptions"
  >,
): StaticHotelRecord {
  return {
    ...input,
    slug: input.id,
    propertyType: "Hotel",
    currency: "USD",
    imageUrls: buildStaticHotelGallery(input.imageUrl, input.id),
    roomOptions: buildPlanningRooms({
      hotelId: input.id,
      roomSummary: input.roomSummary,
      bedSummary: input.bedSummary,
      basePrice: input.indicativeNightlyPrice,
    }),
  };
}

