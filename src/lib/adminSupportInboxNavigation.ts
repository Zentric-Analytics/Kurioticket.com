// Four categories come from the web/mobile Support form. Account deletion
// tickets are generated by the account deletion workflow.
export const supportCategoryOptions = [
  { value: "", label: "All categories" },
  { value: "search-help", label: "Search help" },
  { value: "price-alerts", label: "Price alerts" },
  { value: "redirect", label: "Partner redirect" },
  { value: "account", label: "Account help" },
  { value: "account_deletion", label: "Account deletion" },
] as const;

export function supportCategoryLabel(category: string) {
  const known = supportCategoryOptions.find(option => option.value === category);
  if (known) return known.label;
  const cleaned = category.replace(/[_-]+/g, " ").trim();
  return cleaned ? cleaned[0].toUpperCase() + cleaned.slice(1) : "Unknown";
}

export function supportCategoryChoices(selectedCategory: string) {
  // Legacy/unknown categories in saved URLs remain selectable and readable.
  return supportCategoryOptions.some(option => option.value === selectedCategory) || !selectedCategory
    ? [...supportCategoryOptions]
    : [...supportCategoryOptions, { value: selectedCategory, label: supportCategoryLabel(selectedCategory) }];
}

/** Changing any filter starts on page one; retain all other scoped filters. */
export function supportInboxHref(base: URLSearchParams, changes: Record<string, string>) {
  const params = new URLSearchParams(base);
  params.delete("cursor");
  for (const [key, value] of Object.entries(changes)) {
    if (value) params.set(key, value);
    else params.delete(key);
  }
  const query = params.toString();
  return "/admin/support" + (query ? "?" + query : "");
}


/** Keep inbox return links on the Support route; never accept an arbitrary URL. */
const INBOX_RETURN_KEYS = ["status", "priority", "category", "q", "from", "to", "limit", "cursor"] as const;

function scopedInboxReturnQuery(params: URLSearchParams) {
  const scoped = new URLSearchParams();
  for (const key of INBOX_RETURN_KEYS) {
    const value = params.get(key);
    if (value) scoped.set(key, value);
  }
  return scoped.toString();
}

export function supportTicketDetailHref(ticketId: string, inboxParams: URLSearchParams) {
  const query = scopedInboxReturnQuery(inboxParams);
  return "/admin/support/" + encodeURIComponent(ticketId) + (query ? "?inbox=" + encodeURIComponent(query) : "");
}

export function supportInboxReturnHref(inbox: string | undefined) {
  const query = scopedInboxReturnQuery(new URLSearchParams((inbox || "").slice(0, 2048)));
  return "/admin/support" + (query ? "?" + query : "");
}
